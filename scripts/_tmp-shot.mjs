import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge' })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const p = await ctx.newPage()
await p.goto('http://localhost:3100/achats-groupes/nouveau?productId=6b069908a8c52376f0f28141', { waitUntil: 'load', timeout: 480000 })
await p.waitForSelector('text=Votre quantité', { timeout: 480000 })
await p.waitForFunction(() => document.querySelector('input[required]')?.value, null, { timeout: 300000 }); await p.waitForTimeout(1500)
const qty = p.locator('#group-initial-qty')
await qty.scrollIntoViewIfNeeded()
const before = await qty.inputValue()
await p.locator('[aria-label="Augmenter la quantité"]').click()
const after = await qty.inputValue()
const box = await qty.boundingBox()
const covered = await p.evaluate(() => { const el = document.getElementById('group-initial-qty'); const r = el.getBoundingClientRect(); const top = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return top === el || el.contains(top) ? 'visible' : 'recouvert par ' + top?.outerHTML.slice(0, 80) })
const suggestions = await p.locator('text=Non groupé').count()
console.log({ before, after, box, covered, suggestions })
await p.screenshot({ path: 'C:/Users/ASUS/AppData/Local/Temp/g-wiz-fix.png' })
await b.close()
